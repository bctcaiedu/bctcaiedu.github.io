  function iptAllows(m, port, proto, src) {
    for (const r of ipt(m).INPUT) {
      if (r.i === 'lo') continue;
      if (r.state && !/NEW/.test(r.state)) continue;
      if (r.p && r.p !== 'all' && r.p !== proto) continue;
      if (r.dport && r.dport !== port) continue;
      if (r.sport) continue;
      if (r.s && r.s !== '0.0.0.0/0' && !LX.ipInCidr(src, r.s)) continue;
      if (r.t === 'ACCEPT') return true;
      if (r.t === 'REJECT') return 'reject';
      if (r.t === 'DROP') return false;
    }
    return true;
  }
  function seclistAllows(m, port, proto, src) {
    return seclist(m).some((r) => r.p === proto && String(r.port).split(/[,-]/).length && portIn(r.port, port) && (r.src === '0.0.0.0/0' || LX.ipInCidr(src, r.src)));
  }
  function portIn(spec, port) {
    return String(spec).split(',').some((p) => { if (p.includes('-')) { const [a, b] = p.split('-').map(Number); return port >= a && port <= b; } return +p === port; });
  }
  LX.extraFw = function (m, port, proto, src) {
    if (!seclistAllows(m, port, proto, src)) return false;
    const r = iptAllows(m, port, proto, src);
    return r;
  };

